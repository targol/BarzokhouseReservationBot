def _load_json_data(filename: str, default_data: dict) -> dict:
    """بارگذاری اطلاعات اتاق‌ها یا غذاها از فایل JSON خارجی برای جلوگیری از بازنویسی تنظیمات کاربر"""
    try:
        current_dir = os.path.dirname(os.path.abspath(__file__))
        file_path = os.path.join(current_dir, filename)
        if os.path.exists(file_path):
            with open(file_path, "r", encoding="utf-8") as f:
                loaded = json.load(f)
                if isinstance(loaded, dict) and loaded:
                    return loaded
    except Exception:
        pass
    return default_data

